/** Extract the original offline bank artwork and crop geometry from Android. */
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const websiteRoot = fileURLToPath(new URL('../', import.meta.url));
const source = process.argv[2] || fileURLToPath(new URL('../../Depositly/app/assets/index.html', import.meta.url));
const html = await readFile(source, 'utf8');
const match = html.match(/const BankCatalog=(\[[\s\S]*?\]);/);
if (!match) throw Error('The Android bank catalog could not be found.');
const catalog = JSON.parse(match[1]);
if (!Array.isArray(catalog) || !catalog.length) throw Error('The Android bank catalog is empty.');
const outputDirectory = path.join(websiteRoot, 'assets', 'banks');
await mkdir(outputDirectory, {recursive: true});
const seen = new Set(), records = [];
let byteCount = 0, logoCount = 0;
for (const bank of catalog) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(bank.id) || seen.has(bank.id)) throw Error('Invalid or duplicate bank filename.');
  seen.add(bank.id);
  const record = {id: bank.id, name: bank.name, aliases: bank.aliases || [], src: null, mime: null, logoSize: bank.logoSize || null, symbolBox: bank.symbolBox || null, symbolClip: bank.symbolClip || null, sha256: null};
  for (const dimension of [record.logoSize, record.symbolBox, ...(record.symbolClip || [])]) {
    if (dimension && (!Array.isArray(dimension) || !dimension.every(value => typeof value === 'number' && Number.isFinite(value) && value >= 0))) throw Error(`Invalid logo geometry: ${bank.id}`);
  }
  if (bank.logo) {
    const image = /^data:(image\/(?:png|jpeg|svg\+xml));base64,([a-zA-Z0-9+/=\r\n]+)$/.exec(bank.logo);
    if (!image) throw Error(`Unsupported bundled image data: ${bank.id}`);
    const extension = {'image/png': 'png', 'image/jpeg': 'jpg', 'image/svg+xml': 'svg'}[image[1]];
    const content = Buffer.from(image[2], 'base64');
    if (!content.length) throw Error(`Empty bundled logo: ${bank.id}`);
    if (!record.logoSize || record.logoSize.length !== 2 || record.logoSize.some(value => value <= 0)) throw Error(`Missing bundled image dimensions: ${bank.id}`);
    record.src = `/assets/banks/${bank.id}.${extension}`;
    record.mime = image[1];
    record.sha256 = createHash('sha256').update(content).digest('hex');
    await writeFile(path.join(outputDirectory, `${bank.id}.${extension}`), content);
    byteCount += content.length;
    logoCount++;
  }
  records.push(record);
}
const module = `// Generated by scripts/extract-bank-assets.mjs from the Android BankCatalog.\n// Original artwork and symbol crop geometry are preserved without modification.\nexport const BANK_LOGO_DATA = ${JSON.stringify(records, null, 2)};\n`;
await writeFile(path.join(websiteRoot, 'assets', 'bank-logos.js'), module, 'utf8');
console.log(`Extracted ${logoCount} original bank logos (${byteCount} bytes) for ${records.length} institutions.`);
